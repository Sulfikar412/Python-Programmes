a = int(input("Enter a number: "))

print("Assignment Operators")
print("--------------------")

x = a
print("Assign        (x = a)    :", x)

x += 5
print("Add & Assign  (x += 5)   :", x)

x -= 3
print("Sub & Assign  (x -= 3)   :", x)

x *= 2
print("Mul & Assign  (x *= 2)   :", x)

x //= 3
print("Div & Assign  (x //= 3)  :", x)

x **= 2
print("Exp & Assign  (x **= 2)  :", x)

x %= 5
print("Mod & Assign  (x %= 5)   :", x)
